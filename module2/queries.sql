-- =====================================================================

-- Главный запрос задания:
-- "Процент загрузки автомобиля – отношение общего количества килограммов
-- груза, загруженного на автомобиль, к общей вместимости автомобиля
-- (грузоподъемность), указанной в килограммах."
--
-- Источник загрузки: суммарный вес груза по заказам, связанным с ТС через
-- маршрутные листы. Используем LEFT JOIN, чтобы видеть и пустые
-- (незагруженные) автомобили со значением 0%.

SELECT
    тс.id_тс,
    тс.гос_номер,
    марк.название || ' ' || мод.название       AS марка_модель,
    мод.грузоподъемность_кг                    AS вместимость_кг,
    COALESCE(SUM(з.вес_груза_кг), 0)           AS загружено_кг,
    ROUND(
        COALESCE(SUM(з.вес_груза_кг), 0) * 100.0
        / мод.грузоподъемность_кг,
        2
    )                                          AS процент_загрузки
FROM Транспортные_средства тс
JOIN Модели_ТС мод ON мод.id_модели = тс.id_модели
JOIN Марки_ТС марк ON марк.id_марки = мод.id_марки
LEFT JOIN Маршрутные_листы мл ON мл.id_тс = тс.id_тс
LEFT JOIN Заказы з ON з.id_заказа = мл.id_заказа
GROUP BY
    тс.id_тс,
    тс.гос_номер,
    марк.название,
    мод.название,
    мод.грузоподъемность_кг
ORDER BY процент_загрузки DESC, тс.гос_номер;


-- =====================================================================
-- Вспомогательный запрос: только загруженные автомобили (для отчета логиста).
-- =====================================================================

SELECT
    тс.гос_номер,
    марк.название || ' ' || мод.название AS марка_модель,
    SUM(з.вес_груза_кг)                  AS загружено_кг,
    мод.грузоподъемность_кг              AS вместимость_кг,
    ROUND(
        SUM(з.вес_груза_кг) * 100.0 / мод.грузоподъемность_кг,
        2
    )                                    AS процент_загрузки
FROM Транспортные_средства тс
JOIN Модели_ТС мод ON мод.id_модели = тс.id_модели
JOIN Марки_ТС марк ON марк.id_марки = мод.id_марки
JOIN Маршрутные_листы мл ON мл.id_тс = тс.id_тс
JOIN Заказы з ON з.id_заказа = мл.id_заказа
GROUP BY тс.id_тс
ORDER BY процент_загрузки DESC;


-- =====================================================================
-- Загрузка по модели (средняя по модельной линейке).
-- =====================================================================

SELECT
    марк.название || ' ' || мод.название AS марка_модель,
    мод.грузоподъемность_кг              AS вместимость_кг,
    ROUND(AVG(заказы.суммарно_кг * 100.0 / мод.грузоподъемность_кг), 2)
                                         AS средняя_загрузка_процент
FROM Модели_ТС мод
JOIN Марки_ТС марк ON марк.id_марки = мод.id_марки
JOIN Транспортные_средства тс ON тс.id_модели = мод.id_модели
LEFT JOIN (
    SELECT мл.id_тс AS id_тс,
           SUM(з.вес_груза_кг) AS суммарно_кг
    FROM Маршрутные_листы мл
    JOIN Заказы з ON з.id_заказа = мл.id_заказа
    GROUP BY мл.id_тс
) AS заказы ON заказы.id_тс = тс.id_тс
GROUP BY мод.id_модели
ORDER BY средняя_загрузка_процент DESC NULLS LAST;
