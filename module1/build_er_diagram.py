from pathlib import Path

from graphviz import Digraph


def make_table(label: str, columns: list[tuple[str, str]]) -> str:
    """Сформировать HTML-таблицу для узла графа.

    columns - список кортежей (имя_атрибута, метка) где метка может быть
    'PK' (первичный ключ), 'FK' (внешний), '' (обычный атрибут) или 'PK,FK'.
    """
    rows = (
        f'<TR><TD BGCOLOR="#1f4e79" COLSPAN="2">'
        f'<FONT COLOR="white"><B>{label}</B></FONT></TD></TR>'
    )
    for name, tag in columns:
        if "PK" in tag and "FK" in tag:
            mark = "PK, FK"
            color = "#fff2cc"
        elif "PK" in tag:
            mark = "PK"
            color = "#fff2cc"
        elif "FK" in tag:
            mark = "FK"
            color = "#dae8fc"
        else:
            mark = ""
            color = "white"
        mark_cell = f"<I>{mark}</I>" if mark else "&nbsp;"
        rows += (
            f'<TR><TD ALIGN="LEFT" BGCOLOR="{color}">{name}</TD>'
            f'<TD ALIGN="LEFT" BGCOLOR="{color}">{mark_cell}</TD></TR>'
        )
    return f'<<TABLE BORDER="0" CELLBORDER="1" CELLSPACING="0">{rows}</TABLE>>'


